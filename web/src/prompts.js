// 提笔话题：信纸空着时，淡淡给一句引子。按日子挑，也可以换一句；心情邮票贴上了，就挑合心情的。
const COMMON = [
  '今天让你笑出来的一件事是？',
  '今天吃到的最好吃的一样东西是什么？',
  '有没有一句话，今天很想对谁说？',
  '今天走过的路上，看见了什么？',
  '如果把今天写成一首歌，它叫什么名字？',
  '今天有没有哪一刻，你觉得自己做得不错？',
  '最近在期待的一件小事是？',
  '今天的天空是什么颜色的？',
  '有没有一首歌，今天一直在脑子里转？',
  '今天想谢谢谁？为什么？',
  '如果明天可以只做一件事，你想做什么？',
  '最近读到、听到的哪句话留在了心里？',
  '今天有什么事，比想象中简单？',
  '写一写此刻窗外的声音。',
  '今天的你，和一年前的你有什么不一样？',
  '有什么想对未来的自己交代的？',
  '这周最想留住的一个画面是？',
  '今天有没有被谁温柔地对待？',
]
const BY_MOOD = {
  sunny: ['今天的好心情，是从哪一刻开始的？', '把今天的晴朗分一点给明天：写下它。'],
  warm: ['今天被什么温暖到了？', '有没有想拥抱的人？'],
  calm: ['此刻的平静里，有什么声音？', '今天哪一段时间过得最安稳？'],
  tired: ['今天辛苦了。最累的是哪一段？', '如果现在可以休息，你最想怎么歇？'],
  rainy: ['不开心的话，写下来就好，我在听。', '有什么事压在心上，想说说吗？'],
  tangled: ['把乱糟糟的念头一条条写下来，会轻一些。', '现在最放不下的是哪件事？'],
  missing: ['你在想念谁？想对 TA 说什么？', '想念的那个人，现在会在做什么？'],
  fired: ['今天想攻下的是什么？', '给正在努力的自己写一句话。'],
}

function hash(text) {
  let h = 2166136261
  for (const ch of text) h = Math.imul(h ^ ch.codePointAt(0), 16777619)
  return h >>> 0
}

export function promptFor(date, mood = '', turn = 0) {
  const pool = [...(BY_MOOD[mood] || []), ...(BY_MOOD[mood] || []), ...COMMON]
  return pool[(hash(`${date}|${mood}`) + turn) % pool.length]
}
