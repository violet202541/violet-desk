export const SPACE = 26
export const GAP = 6

export function layout(text) {
  let x = 0
  const glyphs = []
  for (const raw of String(text).toLowerCase()) {
    if (raw === ' ') {
      x += SPACE
      continue
    }
    const glyph = GLYPHS[raw]
    if (!glyph) continue
    glyphs.push({ ...glyph, x, char: raw })
    x += glyph.w + GAP
  }
  return { glyphs, width: Math.max(0, x - GAP) }
}
